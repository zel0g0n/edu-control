/** O'zbekcha matnda "sinf" so'zini "guruh"ga (bosh harf saqlanadi). */
export function uzCenterWords(text: string): string {
  return text.replace(/\b([Ss])inf(?!dosh)/g, (_, s: string) => (s === "S" ? "Guruh" : "guruh"));
}
